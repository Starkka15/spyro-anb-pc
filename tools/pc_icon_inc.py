# Writes src/save_icon.inc: the PC save icon (tools/pc_icon.py) as 64x64
# 0xAARRGGBB words, the layout the texture decoder produces.
#   python tools/pc_icon.py icon.png preview.png
#   python tools/pc_icon_inc.py icon.png src/save_icon.inc
import sys
from PIL import Image
im = Image.open(sys.argv[1]).convert('RGBA')
assert im.size == (64, 64)
raw = im.tobytes()
px = [tuple(raw[i:i + 4]) for i in range(0, len(raw), 4)]
with open(sys.argv[2], 'w', newline='\r\n') as f:
    f.write('/* Generated by tools/pc_icon_inc.py from tools/pc_icon.py. */\n')
    for i in range(0, len(px), 8):
        f.write(' '.join('0x%02X%02X%02X%02Xu,' % (a, r, g, b) for r, g, b, a in px[i:i + 8]) + '\n')
